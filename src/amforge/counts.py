"""「长度 ÷ 间距 → 整数个数」的取整助手（T3 / #24，2026-10-08）。

背景：T1（D4，§25.7）给 ``geometry._grid_axes`` 做过一次 ``1e-9`` 相对容差吸附，原因是
``12.5*1e-6`` 比字面量 ``12.5e-6`` 小 1 ulp，件厚恰为 dx 整数倍时 ``ceil`` 多出一层（161602 vs
156849 个体素，峰值温度差 0.53%）。同一模式在全树还有 **11 个位点**（普查与逐位点实测见
``docs/evidence/2026-10-08/am_t3_intsnap_probe.py``），它们都用两个物理长度相除再取整，用来决定
**域/栅格/路径有多大**，改前全部裸 ``ceil``/``floor``。改前 **31/84** 例在
{字面量, −1ulp, +1ulp, ``µm 数值×1e-6``} 四种**保值**拼写之间整数改变（11 位点里 10 位有翻转），
改后 **0/84**（``am_t3_intsnap_probe_pre.log`` ／ ``..._post.log``）。实测形态：

* 基板厚 20 格（``250e-6 / 12.5e-6``）→ 比值 ``20.000000000000004`` → ``ceil`` 给 **21 格**；
* 3 层粉末床（``n_layers·lt`` 对 ``2·d50``）→ 换 1 ulp 拼写 → ``floor+1`` 掉一层 ⇒ 粒子数 100→75；
* hatch 线数 ``400µm/100µm`` → ``+1 ulp`` 的 hatch → **少一条扫描线**。

本模块把那**一个**约定（相对容差 ``1e-9 · max(1, |比值|)``）单点化，供 amforge 全树使用。
``diffmech`` 位于 ``amforge`` 之下（依赖单向 ``amforge → diffmech``），不能反向 import 本模块
⇒ 那 3 处按同款宽度**内联**，由上述探针的「文本绑定」列守两包漂移（§26.17 的教训）。

为什么是 ``1e-9``：一次 ulp 抖动 ≈1e-16，两次运算的复合 ≈1e-15，而真实几何余量（模型精度、
层厚取整、hatch 留边）远大于体素的 1e-9 倍 ⇒ 这个宽度吃得下**拼写**、吃不下**设计余量**。
探针 K3 实测分居两侧：比值高出整数 1e-10（相对）被吸附，高出 1e-8 **不**被吸附。

口径提醒：本模块只统一"同一比值的取整稳定性"，**不**统一 ceil / round / floor+1 三套口径——
后者是 #31（与 #22 的 ``beam_radius`` √2 分裂同族）。

同一个普查还抓到**另一类**机制、本模块**故意不管**：``process.zigzag_segments`` 的 ``diag``
带**绝对** ``+1e-12`` fudge（还要兼职当道长下限），在 0.2828mm 跨度上＝ ``3.5355e-9`` 相对
＝本容差的 3.5 倍 ⇒ 带宽吸不到它，整除跨度处**系统性多算一道**（实测 `q=4/8/20 → 5/9/21`，
±1ulp 换写**不**翻转 ⇒ 扰动型探针对它无效，是 K2b 的预测值列抓的）。把它吸进带内＝把容差写宽
凑绿（违 N4），改它＝动扫描几何 ⇒ 另立台账 **#32**。
"""
from __future__ import annotations

import math

__all__ = ["TOL_REL", "count_ceil", "count_floor"]

TOL_REL = 1e-9


def count_ceil(ratio: float) -> int:
    """``ceil(ratio)``，但比值落在整数**上方** ``1e-9·max(1,|ratio|)`` 内时吸附到该整数。

    用于「铺满长度 L 需要几格」类计数（``n·step ≥ L``）。容差向**下**扣 ⇒ 只会减少格数，
    不会凭空多铺一层；探针 K4 因此要求改后覆盖不退化（少覆盖不得超过容差宽度）。
    """
    r = float(ratio)
    return int(math.ceil(r - TOL_REL * max(1.0, abs(r))))


def count_floor(ratio: float) -> int:
    """``floor(ratio)``，但比值落在整数**下方** ``1e-9·max(1,|ratio|)`` 内时吸附到该整数。

    用于 ``floor(ratio) + 1`` 的格点/扫描线计数（端点都算）。容差向**上**加 ⇒ 只会减少线数。
    """
    r = float(ratio)
    return int(math.floor(r + TOL_REL * max(1.0, abs(r))))
